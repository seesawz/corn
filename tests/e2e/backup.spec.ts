import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('导出完整本地备份，在另一个浏览器空间合并导入并去重', async ({ page, browser }) => {
  await page.goto('./')
  await page.getByRole('button', { name: '暂不登录，本地使用' }).click()
  await page.getByRole('button', { name: '新建项目', exact: true }).click()
  await page.getByRole('textbox', { name: '项目名称' }).fill('备份项目')
  await page.getByRole('button', { name: '创建项目', exact: true }).click()
  await page.locator('.composer-input').fill('备份任务')
  await page.locator('.composer-input').press('Enter')
  await expect(page.getByRole('button', { name: '导入备份', exact: true })).toBeEnabled()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出备份', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^corn-backup-.*\.json$/)
  const backup = await readFile((await download.path())!)
  expect(JSON.parse(backup.toString()).workspace.tasks[0].text).toBe('备份任务')
  const target = await browser.newContext()
  try {
    const other = await target.newPage()
    await other.goto(page.url())
    await other.getByRole('button', { name: '暂不登录，本地使用' }).click()
    await other.locator('.composer-input').fill('已有任务')
    await other.locator('.composer-input').press('Enter')
    await expect(other.getByRole('button', { name: '导入备份', exact: true })).toBeEnabled()
    const upload = other.getByLabel('选择 corn 备份文件')
    await upload.setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: backup })
    await expect(other.getByLabel('本地数据备份').getByRole('status')).toContainText('已导入 1 个项目、1 条任务')
    await expect(other.getByText('已有任务', { exact: true })).toBeVisible()
    await other.getByRole('button', { name: /^备份项目 \d+$/ }).click()
    await expect(other.getByText('备份任务', { exact: true })).toBeVisible()
    await expect(other.getByRole('button', { name: '导入备份', exact: true })).toBeEnabled()
    await upload.setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: backup })
    await expect(other.getByLabel('本地数据备份').getByRole('status')).toContainText('跳过 1 条已有任务')
    await expect(other.locator('.task')).toHaveCount(1)
    await other.reload()
    await expect(other.getByText('备份任务', { exact: true })).toBeVisible()
    await other.getByLabel('选择 corn 备份文件').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{bad') })
    await expect(other.getByRole('alert')).toContainText('格式不正确')
    await expect(other.getByText('备份任务', { exact: true })).toBeVisible()
    await other.setViewportSize({ width: 375, height: 812 })
    expect(await other.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  } finally { await target.close() }
})
